// Builds the engine's WebAssembly module and embeds it in the TypeScript
// sources: cargo (release, wasm32), wasm-opt -O3, then base64 into
// packages/postext/src/knuthPlass/wasm/bytes.generated.ts, which the engine
// compiles at run time (#779). Run after any change to rust/crates:
//
//   node rust/scripts/build-wasm.mjs
//
// Needs rustup's toolchain with the wasm32-unknown-unknown target and
// binaryen's wasm-opt on PATH (rust/README.md).

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const run = (cmd, args) => execFileSync(cmd, args, { cwd: root, stdio: 'inherit' });

run('cargo', ['build', '--release', '--target', 'wasm32-unknown-unknown', '-p', 'postext-wasm']);
const raw = resolve(root, 'target/wasm32-unknown-unknown/release/postext_wasm.wasm');
const opt = resolve(root, 'target/postext_wasm.opt.wasm');
run('wasm-opt', ['-O3', raw, '-o', opt]);

const bytes = readFileSync(opt);
const base64 = bytes.toString('base64');
const out = resolve(root, '../packages/postext/src/knuthPlass/wasm/bytes.generated.ts');
const lines = base64.match(/.{1,100}/g) ?? [];
writeFileSync(out, `// Generated by rust/scripts/build-wasm.mjs from rust/crates: do not edit.
// The Rust line breaker compiled to WebAssembly (${bytes.length} bytes).

export const LINEBREAK_WASM_BASE64 =
${lines.map((l) => `  '${l}'`).join(' +\n')};
`);
console.log(`${out}: ${bytes.length} bytes of WebAssembly`);
