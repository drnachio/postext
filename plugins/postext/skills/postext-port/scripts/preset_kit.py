def manifest_files(manifest: Any, project: Path) -> set[str]:
    """The project files a manifest names: every string value of it that is
    the relative path of a file in the project (chapters, resource files,
    print masters, posters, font variants, the thumbnail, an output
    profile)."""
    root = project.resolve()
    found: set[str] = set()

    def walk(node: Any) -> None:
        if isinstance(node, dict):
            for v in node.values():
                walk(v)
        elif isinstance(node, list):
            for v in node:
                walk(v)
        elif isinstance(node, str) and 0 < len(node) < 512 and "\n" not in node and not node.startswith(("/", "{")):
            rel = os.path.normpath(node).replace(os.sep, "/")
            if not rel.startswith("../") and rel != ".." and (root / rel).is_file():
                found.add(rel)
    walk(manifest)
    return found


def _excluded(rel: str, patterns: list[str]) -> bool:
    parts = rel.split("/")
    for pat in patterns:
        pat = pat.rstrip("/")
        if fnmatch.fnmatch(rel, pat) or any(fnmatch.fnmatch("/".join(parts[:i]), pat) for i in range(1, len(parts))):
            return True
    return False


def pack_files(project: Path, manifest: dict, manifest_only: bool = False, exclude: list[str] = ()) -> list[str]:
    """The relative paths `pack` zips, sorted."""
    skip_fonts = {v["file"] for f in manifest.get("fonts", []) if f.get("redistributable") is False for v in f["variants"]}
    named = manifest_files(manifest, project) | {"preset.json"} if manifest_only else None
    if named is not None:
        return sorted(rel for rel in named if rel not in skip_fonts and not _excluded(rel, list(exclude))
                      and not any(part.startswith(".") for part in rel.split("/")))
    out = []
    for p in sorted(project.rglob("*")):
        rel = p.relative_to(project).as_posix()
        if not p.is_file() or any(part.startswith(".") for part in rel.split("/")):
            continue
        if rel in skip_fonts or _excluded(rel, list(exclude)):
            continue
        # Pagination caches go stale with the engine: the sandbox lays out afresh.
        if rel.startswith(("source/", "__pycache__/")) or (rel.startswith("layouts") and rel.endswith(".json")):
            continue
        if p.suffix in (".py",) or rel in ("resources.json", "chapters.json", "report.md", "roles.json"):
            continue
        out.append(rel)
    return out


def packed_manifest(manifest: dict, fallbacks: dict[str, str] | None = None) -> tuple[dict, list[str]]:
    """The manifest as the pack writes it (postext >= 1.42): a family left out
    because it is not redistributable keeps its entry with no file and its
    `fallback` (the open family every host sets its faces in); `fallbacks`
    gives (or replaces) the stand-in per family name. Returns (manifest, the
    names of the families left out with no fallback)."""
    out = json.loads(json.dumps(manifest))
    bare: list[str] = []
    for f in out.get("fonts", []):
        if fallbacks and f.get("name") in fallbacks:
            f["fallback"] = fallbacks[f["name"]]
        if f.get("redistributable") is False and f.get("variants"):
            if f.get("fallback"):
                f["variants"] = []
            else:
                bare.append(f["name"])
    return out, bare


def parse_fallbacks(specs: list[str] | None) -> dict[str, str]:
    """`--fallback "Adobe Garamond Pro=EB Garamond"` (repeatable) as {family: stand-in}."""
    out: dict[str, str] = {}
    for spec in specs or []:
        family, sep, stand_in = spec.partition("=")
        if not sep or not family.strip() or not stand_in.strip():
            raise SystemExit(f"--fallback wants FAMILY=OPEN FAMILY, got {spec!r}")
        if family.strip() == stand_in.strip():
            raise SystemExit(f"--fallback {spec!r}: the stand-in must be another family")
        out[family.strip()] = stand_in.strip()
    return out


CHECK_RESULT = "work/check.json"  # where `composed_check.py check --json-out` writes the result


def _checked_project(res: dict) -> Path | None:
    """The project folder a saved check result was written for (None for a
    bundle or an unreadable target)."""
    target = str(res.get("target") or "").split("!", 1)[0]
    if not target or target.endswith(".postext"):
        return None
    p = Path(target).resolve()
    return p.parent if p.name == "preset.json" else p


def check_refusal(project: Path, check: str | None = None) -> str | None:
    """Why the book must not be packed: the saved result of `composed_check.py
    check` says it failed: --check FILE, else work/check.json in the project
    or in the current folder when it was written for this project. None when
    it passed or no result is saved."""
    project = project.resolve()
    if check:
        path = Path(check)
        if not path.is_file():
            return f"--check {check}: no such file"
        candidates = [path]
    else:
        candidates = [p for p in dict.fromkeys([project / CHECK_RESULT, Path.cwd() / CHECK_RESULT]) if p.is_file()]
    for path in candidates:
        try:
            res = json.loads(path.read_text(encoding="utf-8"))
        except ValueError:
            return f"{path}: not the JSON of `composed_check.py check --json-out`"
        if check or _checked_project(res) in (None, project):
            break
    else:
        return None
    if res.get("passed") is not False:
        return None
    fails = sum(len(e.get("fail") or []) for e in (res.get("editions") or {}).values())
    return (f"{path} says the composed-page check failed ({fails} failing warning(s), "
            f"{res.get('overlaps', 0)} overlap(s)). Fix each failure (an overlap: a fix the check lists, "
            "overlap: \"allow\" when the source prints it so, or an entry with its reason in composed-check.json, "
            "raised with the user), run `composed_check.py check … --json-out work/check.json` again, then pack. "
            "--ignore-check packs anyway")


def cmd_pack(args) -> None:
    project = Path(args.project).resolve()
    manifest = json.loads((project / "preset.json").read_text(encoding="utf-8"))
    refusal = None if getattr(args, "ignore_check", False) else check_refusal(project, getattr(args, "check", None))
    if refusal:
        raise SystemExit(refusal)
    out = Path(args.out or f"{manifest['id']}.postext").resolve()
    skip_fonts = {v["file"] for f in manifest.get("fonts", []) if f.get("redistributable") is False for v in f["variants"]}
    files = pack_files(project, manifest, args.manifest_only, args.exclude or [])
    known = {f.get("name") for f in manifest.get("fonts", [])}
    fallbacks = parse_fallbacks(args.fallback)
    for family in fallbacks:
        if family not in known:
            raise SystemExit(f"--fallback: the manifest has no font family {family!r} (families: {sorted(n for n in known if n)})")
    packed, bare = packed_manifest(manifest, fallbacks)
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for rel in files:
            if rel == "preset.json" and packed != manifest:
                z.writestr(rel, json.dumps(packed, ensure_ascii=False, indent=2) + "\n")
            else:
                z.write(project / rel, rel)
    if skip_fonts:
        print(f"left out {len(skip_fonts)} non-redistributable font file(s)")
    for f in packed.get("fonts", []):
        if f.get("redistributable") is False and f.get("fallback"):
            print(f"  {f['name']}: set in {f['fallback']} where its files are not (postext >= 1.42)")
    for name in bare:
        print(f"  {name}: no fallback, so the plain bundle sets it in the generic face (wider; frames overflow). "
              f"Measure the open candidates with `fonts.py width <licensed .ttf> <candidate .ttf>... --text-from chapters/<lang>/` "
              f"and pack with --fallback \"{name}=<open family>\"")
    print(f"wrote {out} ({len(files)} files)")


