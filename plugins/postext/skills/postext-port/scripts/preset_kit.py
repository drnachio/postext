#!/usr/bin/env python3
"""Helpers and commands to assemble a Postext project (a *preset bundle*).

A bundle is a folder the Postext sandbox can open:

    <project>/
      preset.json            manifest (generated by build_preset.py; don't hand-edit)
      build_preset.py        YOUR generator: measured design constants -> config
      chapters/<lang>/NN-slug.md
      resources/             figures (svg/png/jpg/webp/gif) + optional .pdf print masters
      fonts/                 ttf / otf / woff2 single faces
      resources.json         resource list (figures, tables) read by build_preset.py
      thumbnail.jpg          optional

Commands:
  preset_kit.py init <project> --id my-book --name "My book" --lang es [--lang en]
      Create the folders and a build_preset.py to fill in.
  preset_kit.py pack <project> [--out my-book.postext]
      Zip the bundle as a .postext file (Sandbox > Projects > Import .postext).
  preset_kit.py index <presets-root>
      Write <presets-root>/index.json listing every preset.json below it (for
      POSTEXT_PRIVATE_PRESETS_DIR or a static host).
  preset_kit.py fonts <project>
      Print the `fonts` entries for the faces in <project>/fonts (family, weight,
      style read from the font files; needs fontTools, else guessed from names).

Library (import from build_preset.py):
  mm(12) / pt(9.5) / em(1.2)          Dimension objects
  color("#1d3557", "main-color")       ColorValue linked to a palette entry
  palette({"main-color": ("Main", "#1d3557"), ...})
  text_el(...), rule_el(...), box_el(...), image_el(...)   design elements
  place(anchor, edge, x=0, y=0, width=None, height=None)   ElementPlacement
  bitmap(id, file, caption, ...), svg(id, file, ...), table(id, rows, ...)
  chapters_from_dir(project, lang)     [{title, file}] from chapters/<lang>/*.md
  font_families(project)               `fonts` entries from fonts/
  write_manifest(project, manifest)    writes preset.json (+ fingerprint.json)
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import sys
import zipfile
from pathlib import Path
from typing import Any

