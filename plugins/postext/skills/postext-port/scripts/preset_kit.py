# The configuration rules the manifest's `config` is written for (postext's
# CONFIG_VERSION). A manifest without it is read as a postext 1.4 bundle:
# heading breaks, maths size, the space around inline figures (in boxes too),
# heading marks, drop-cap sizes, the room under a colon line that
# introduces a list, the lines a box cut leaves of a paragraph, the line
# breaks after a closed dash and after a compound's hyphen, the breaking of
# ragged text, the split of a paragraph under a heading and the space under
# :::paragraphs containers pinned to 1.4. A manifest stamped 8 (postext 1.5
# to 1.22) gets the rules-9 pins: a :::verse poem with no separator as
# centred hemistichs, a first-line indent dropped from a style that hangs, a
# backslash ending a line printed. A manifest stamped 9 (postext 1.23) gets
# the rules-10 pin: a line of verse a little too wide turns over instead of
# tightening its word spaces. A manifest stamped 10 (postext 1.24) gets the
# rules-11 pin: a horizontal page on a character grid stays balanced. An
# manifest stamped 11 (postext 1.25 to 1.27) gets the rules-12 pin: on a
# character grid the widow rule stays on, and the orphan rule too in the
# Japan region. A manifest stamped 12 (postext 1.28) gets the rules-13
# pins: the text shaped in the language of the page that hosts the layout
# (bodyText.shapingLanguage: 'host') and the box of a task item set as a
# character. A manifest stamped 13 (postext 1.29) gets the rules-14 pin:
# 'host' again when its config names no bodyText.shapingLanguage, since
# from postext 1.30 a document is shaped in its own language by default.
# Rules 15 (postext 1.34) mark a config that may hold pageTemplates and
# labelStyles and pin nothing, so 14 reads the same. Rules 16 (postext 1.48)
# mark a config whose templates may hold connectors and pin nothing either.
# 17 (1.52) sets a paragraph style's unset type fields in a box's body;
# 16 and older read with the document's (bodyText.paragraphStylesInBoxes).
# 18 (1.52) gives a mark style that names no borderRadius square ends; 17 and
# older keep 0.2em when the text has a :mark.
# 19 (1.53) lets formatted text break after a slash between two words; 20
# (1.54) reads a fence in a notation language as a music score. 21 (#1209)
# merges each `localized.<lang>.config` over the shared `config` field by
# field (objects key by key, lists of entries with an `id` by id, `levels`
# by level, `null` back to the default, `{id, "$remove": true}` drops an
# entry); 20 and older replace each top-level key it names whole.
# A book ported today is stamped 21 and is shaped in its own language. An
# engine older than 1.23 reads 9 as 8, one older than 1.24 reads 10 as 9,
# one older than 1.25 reads 11 as 10, one older than 1.28 reads 12 as 11,
# one older than 1.30 reads 14 as 13, one older than 1.34 reads 15 as 14.
CONFIG_VERSION = 21

# The rules from which a localized config is an override merged field by
# field (postext's LOCALE_LAYER_RULES).
