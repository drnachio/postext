def chapter_title(md: str) -> str:
    fm = re.match(r"^---\r?\n([\s\S]*?)\r?\n---", md)
    body = md[fm.end():] if fm else md
    m = re.search(r"^#\s+(.+)$", body, re.M)
    if m:
        t = re.sub(r"\s+\{[^{}]*\}\s*$", "", m.group(1))
        return re.sub(r"\s*\\\\\s*", " ", t).strip()
    if fm:
        t = re.search(r'^title:\s*"?(.+?)"?\s*$', fm.group(1), re.M)
        if t:
            return t.group(1)
    return ""


def chapters_from_dir(project: Path | str, lang: str) -> list[dict]:
    """Every chapters/<lang>/*.md in name order (01-…, 02-…)."""
    project = Path(project)
    out = []
    for f in sorted((project / "chapters" / lang).glob("*.md")):
        title = chapter_title(f.read_text(encoding="utf-8")) or f.stem
        out.append({"title": title, "file": f"chapters/{lang}/{f.name}"})
    return out


def font_families(project: Path | str, redistributable: dict[str, bool] | None = None) -> list[dict]:
    """`fonts` entries from project/fonts (ttf/otf/woff2). Family, weight and style
    come from the font tables (fontTools), else from 'Family-BoldItalic' names."""
    project = Path(project)
    fams: dict[str, list[dict]] = {}
    for f in sorted((project / "fonts").glob("*")):
        if f.suffix.lower() not in (".ttf", ".otf", ".woff2"):
            continue
        fam, weight, style = _font_meta(f)
        fams.setdefault(fam, []).append({"weight": weight, "style": style, "file": f"fonts/{f.name}"})
    out = []
    for name, variants in fams.items():
        entry: dict = {"name": name, "variants": sorted(variants, key=lambda v: (v["style"], v["weight"]))}
        if redistributable and redistributable.get(name) is False:
            entry["redistributable"] = False
        out.append(entry)
    return out


_WEIGHTS = {"thin": 100, "extralight": 200, "ultralight": 200, "light": 300, "regular": 400, "book": 400,
            "normal": 400, "medium": 500, "semibold": 600, "demibold": 600, "demi": 600, "bold": 700,
            "extrabold": 800, "ultrabold": 800, "black": 900, "heavy": 900}


def _font_meta(path: Path) -> tuple[str, int, str]:
    try:
        from fontTools.ttLib import TTFont  # type: ignore

        f = TTFont(str(path), lazy=True, fontNumber=0)
        name = f["name"]
        fam = name.getDebugName(16) or name.getDebugName(1) or path.stem
        weight = f["OS/2"].usWeightClass if "OS/2" in f else 400
        italic = bool(f["OS/2"].fsSelection & 1) if "OS/2" in f else False
        if "head" in f and f["head"].macStyle & 2:
            italic = True
        return fam, int(weight), "italic" if italic else "normal"
    except Exception:
        stem = path.stem
        fam, _, sub = stem.partition("-")
        low = sub.lower()
        italic = "italic" in low or "oblique" in low
        low = low.replace("italic", "").replace("oblique", "")
        weight = _WEIGHTS.get(low or "regular", 400)
        return re.sub(r"(?<=[a-z])(?=[A-Z])", " ", fam), weight, "italic" if italic else "normal"


def fingerprint(project: Path | str) -> str:
    project = Path(project)
    h = hashlib.sha1()
    for p in sorted(project.rglob("*")):
        if p.is_file() and p.name not in ("fingerprint.json",) and not p.name.startswith("."):
            st = p.stat()
            h.update(f"{p.relative_to(project)}:{st.st_size}:{int(st.st_mtime)}\n".encode())
    return h.hexdigest()


def write_manifest(project: Path | str, manifest: dict) -> Path:
    """Write preset.json (v2) after checking that every referenced file exists,
    then fingerprint.json (lets the sandbox notice edits)."""
    project = Path(project)
    manifest.setdefault("version", 2)
    missing = []
    chapters = manifest.get("chapters", {})
    specs = chapters if isinstance(chapters, list) else [c for v in chapters.values() for c in v]
    for c in specs:
        if not (project / c["file"]).exists():
            missing.append(c["file"])
    for r in manifest.get("resources", []):
        for k in ("file", "pdfFile"):
            if r.get(k) and not (project / r[k]).exists():
                missing.append(r[k])
    for f in manifest.get("fonts", []):
        for v in f.get("variants", []):
            if not (project / v["file"]).exists():
                missing.append(v["file"])
    if manifest.get("config", {}).get("customFonts"):
        raise ValueError("config.customFonts must not be written: fonts come from the `fonts` array")
    if missing:
        raise FileNotFoundError("missing files: " + ", ".join(missing))
    out = project / "preset.json"
    out.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (project / "fingerprint.json").write_text(json.dumps({"fingerprint": fingerprint(project)}) + "\n", encoding="utf-8")
    return out


