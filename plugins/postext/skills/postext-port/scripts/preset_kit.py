def cmd_init(args) -> None:
    project = Path(args.project)
    langs = args.lang or ["en"]
    for d in ["resources", "fonts", "source"] + [f"chapters/{l}" for l in langs]:
        (project / d).mkdir(parents=True, exist_ok=True)
    build = project / "build_preset.py"
    if build.exists() and not args.force:
        sys.exit(f"{build} exists (use --force)")
    kit_dir = str(Path(__file__).resolve().parent)
    build.write_text(TEMPLATE.format(id=args.id, name=args.name, langs=langs, kit_dir=kit_dir), encoding="utf-8")
    os.chmod(build, 0o755)
    print(f"created {project}/ (chapters/{', chapters/'.join(langs)}, resources/, fonts/, source/, build_preset.py)")


def cmd_pack(args) -> None:
    project = Path(args.project).resolve()
    manifest = json.loads((project / "preset.json").read_text(encoding="utf-8"))
    out = Path(args.out or f"{manifest['id']}.postext").resolve()
    skip_fonts = {v["file"] for f in manifest.get("fonts", []) if f.get("redistributable") is False for v in f["variants"]}
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for p in sorted(project.rglob("*")):
            rel = p.relative_to(project).as_posix()
            if not p.is_file() or any(part.startswith(".") for part in rel.split("/")):
                continue
            if rel.startswith(("source/", "__pycache__/")) or rel in skip_fonts or rel in ("layouts.json",):
                continue
            if p.suffix in (".py",) or rel in ("resources.json", "chapters.json", "report.md", "roles.json"):
                continue
            z.write(p, rel)
    if skip_fonts:
        print(f"left out {len(skip_fonts)} non-redistributable font file(s)")
    print(f"wrote {out}")


def cmd_index(args) -> None:
    root = Path(args.root).resolve()
    presets = []
    for mf in sorted(root.rglob("preset.json")):
        if any(part.startswith(".") for part in mf.relative_to(root).parts):
            continue
        m = json.loads(mf.read_text(encoding="utf-8"))
        entry = {"id": m["id"], "dir": mf.parent.relative_to(root).as_posix(), "name": m["name"]}
        for k in ("description", "locale", "locales", "thumbnail", "license", "credits", "tags"):
            if m.get(k):
                entry[k] = m[k]
        presets.append(entry)
    (root / "index.json").write_text(json.dumps({"version": 1, "presets": presets}, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {root / 'index.json'} ({len(presets)} presets)")


def cmd_fonts(args) -> None:
    print(json.dumps(font_families(args.project), ensure_ascii=False, indent=2))


