def image_size(path: Path) -> tuple[int, int] | None:
    try:
        from PIL import Image  # type: ignore

        with Image.open(path) as im:
            return im.width, im.height
    except Exception:
        pass
    data = path.read_bytes()[:64 * 1024]
    if data[:8] == b"\x89PNG\r\n\x1a\n":
        return int.from_bytes(data[16:20], "big"), int.from_bytes(data[20:24], "big")
    if data[:2] == b"\xff\xd8":
        i = 2
        while i < len(data) - 9:
            if data[i] != 0xFF:
                i += 1
                continue
            marker = data[i + 1]
            length = int.from_bytes(data[i + 2:i + 4], "big")
            if marker in (0xC0, 0xC1, 0xC2):
                return int.from_bytes(data[i + 7:i + 9], "big"), int.from_bytes(data[i + 5:i + 7], "big")
            i += 2 + length
    return None


def svg_size(path: Path) -> tuple[float, float] | None:
    head = path.read_text(encoding="utf-8", errors="ignore")[:4000]

    def num(attr: str) -> float | None:
        m = re.search(rf'\s{attr}="([\d.]+)(pt|px)?"', head)
        return float(m.group(1)) if m else None

    w, h = num("width"), num("height")
    if w and h:
        return w, h
    m = re.search(r'viewBox="\s*[-\d.]+[\s,]+[-\d.]+[\s,]+([\d.]+)[\s,]+([\d.]+)', head)
    return (float(m.group(1)), float(m.group(2))) if m else None


def _placement(position: str | None, span: str | None, **more) -> dict | None:
    p = {k: v for k, v in (("position", position), ("span", span)) if v}
    p.update({k: v for k, v in more.items() if v is not None})
    return p or None


def bitmap(project: Path | str, id_: str, file: str, caption: str = "", *, type_id: str = "figure",
           alt: str | None = None, note: str | None = None, position: str | None = None,
           span: str | None = None, **placement) -> dict:
    """A bitmap resource with its pixel size (Node renderers cannot decode it)."""
    size = image_size(Path(project) / file)
    r = {"id": id_, "typeId": type_id, "kind": "bitmap", "file": file, "caption": caption,
         "altText": alt if alt is not None else re.sub(r"[*_^~]", "", caption)}
    if size:
        r["width"], r["height"] = size
    if note:
        r["note"] = note
    pl = _placement(position, span, **placement)
    if pl:
        r["placement"] = pl
    return r


def svg(project: Path | str, id_: str, file: str, caption: str = "", *, type_id: str = "figure",
        pdf_file: str | None = None, alt: str | None = None, note: str | None = None,
        position: str | None = None, span: str | None = None, **placement) -> dict:
    size = svg_size(Path(project) / file)
    r = {"id": id_, "typeId": type_id, "kind": "svg", "file": file, "caption": caption,
         "altText": alt if alt is not None else re.sub(r"[*_^~]", "", caption)}
    if size:
        r["width"], r["height"] = round(size[0], 2), round(size[1], 2)
    if pdf_file:
        r["pdfFile"] = pdf_file
    if note:
        r["note"] = note
    pl = _placement(position, span, **placement)
    if pl:
        r["placement"] = pl
    return r


def table(id_: str, rows: list[list[Any]], caption: str = "", *, header_rows: int = 1,
          column_widths: list[float] | None = None, style_id: str | None = None,
          type_id: str = "table", note: str | None = None, position: str | None = None,
          span: str | None = None, **placement) -> dict:
    """rows: lists of cells; a cell is a string or a TableCell dict. Header rows
    get isHeader. Merged cells: give the primary cell colSpan/rowSpan and keep a
    {"content": "", "hiddenBy": {"row": r, "col": c}} in every slot it covers."""
    model_rows = []
    for r_i, row in enumerate(rows):
        cells = []
        for cell in row:
            c = {"content": cell} if isinstance(cell, str) else dict(cell)
            if r_i < header_rows and "hiddenBy" not in c:
                c.setdefault("isHeader", True)
            cells.append(c)
        model_rows.append(cells)
    widths = {len(r) for r in model_rows}
    if len(widths) > 1:
        raise ValueError(f"table {id_}: every row needs one cell per column (use hiddenBy for merged slots); got widths {sorted(widths)}")
    model: dict = {"rows": model_rows}
    if header_rows:
        model["headerRowCount"] = header_rows
    if column_widths:
        model["columnWidths"] = column_widths
    t = {"id": id_, "typeId": type_id, "kind": "table", "caption": caption, "table": {"model": model}}
    if style_id:
        t["table"]["styleId"] = style_id
    if note:
        t["note"] = note
    pl = _placement(position, span, **placement)
    if pl:
        t["placement"] = pl
    return t


