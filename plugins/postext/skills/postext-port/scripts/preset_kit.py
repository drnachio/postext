def dim(value: float, unit: str) -> dict:
    return {"value": round(float(value), 4), "unit": unit}


def mm(v: float) -> dict:
    return dim(v, "mm")


def pt(v: float) -> dict:
    return dim(v, "pt")


def em(v: float) -> dict:
    """Only where the reference allows em (line heights, margins of headings,
    lists, callouts…). Geometry and font sizes must be absolute (mm/pt)."""
    return dim(v, "em")


def color(hex_: str, palette_id: str | None = None, model: str = "hex") -> dict:
    c = {"hex": hex_.lower(), "model": model}
    if palette_id:
        c["paletteId"] = palette_id
    return c


def palette(entries: dict[str, tuple[str, str]]) -> list[dict]:
    """{"main-color": ("Main", "#1d3557")} -> colorPalette. Include `main-color`:
    every built-in accent (headings, bold, bullets, callouts…) points at it."""
    return [{"id": k, "name": name, "value": {"hex": hx.lower(), "model": "hex"}} for k, (name, hx) in entries.items()]


def place(anchor: str = "page", edge: str = "top-left", x: float = 0, y: float = 0,
          width: Any = None, height: Any = None, max_width: Any = None, unit: str = "mm") -> dict:
    """ElementPlacement. anchor: 'container' | 'page' | 'bleed' | '#elementId'.
    Offsets are screen directions (+x right, +y down) in `unit`; a right/bottom
    anchored element needs negative offsets to move inwards."""
    p: dict = {"anchor": {"to": anchor, "edge": edge}}
    off = {}
    if x:
        off["x"] = dim(x, unit)
    if y:
        off["y"] = dim(y, unit)
    if off:
        p["offset"] = off
    size = {}
    for k, v in (("width", width), ("height", height), ("maxWidth", max_width)):
        if v is None:
            continue
        size[k] = v if isinstance(v, (str, dict)) else dim(v, unit)
    if size:
        p["size"] = size
    return p


def text_el(id_: str, content: str, placement: dict, *, font: str, size: float, weight: int = 400,
            italic: bool = False, fill: dict | None = None, align: str = "left", valign: str = "top",
            overflow: str | None = None, line_height: float | None = None, uppercase: bool = False,
            letter_spacing: float | None = None, parity: str | None = None, pages: str | None = None,
            **extra) -> dict:
    """Design text element. `content` is a template: {pageNumber}, {chapterTitle},
    {chapterNumber}, {partTitle}, {partNumber}, {title}, {titleText}, {number},
    {attr.<key>}… Set every typographic field: element defaults are not the
    body's. `overflow` left out follows the slot (postext ≥ 1.24): a heading
    or part design wraps, a running head, folio or contents row ends in `…`."""
    el = {"kind": "text", "id": id_, "placement": placement, "content": content,
          "fontFamily": font, "fontSize": pt(size), "fontWeight": weight, "italic": italic,
          "color": fill or color("#000000"), "align": align, "verticalAlign": valign}
    if overflow:
        el["overflow"] = overflow
    if line_height:
        el["lineHeight"] = line_height
    if uppercase:
        el["textTransform"] = "uppercase"
    if letter_spacing:
        el["letterSpacing"] = em(letter_spacing)
    if parity:
        el["parity"] = parity
    if pages:
        el["pages"] = pages
    el.update(extra)
    return el


def rule_el(id_: str, placement: dict, *, direction: str = "horizontal", fill: dict | None = None,
            thickness: float = 0.5, parity: str | None = None, pages: str | None = None) -> dict:
    el = {"kind": "rule", "id": id_, "placement": placement, "direction": direction,
          "color": fill or color("#000000"), "thickness": pt(thickness)}
    if parity:
        el["parity"] = parity
    if pages:
        el["pages"] = pages
    return el


def box_el(id_: str, placement: dict, *, fill: dict | None = None, border: dict | None = None,
           border_width: float | None = None, radius: float | None = None,
           parity: str | None = None, pages: str | None = None) -> dict:
    style: dict = {}
    if fill:
        style["backgroundColor"] = fill
    if border:
        style["borderColor"] = border
    if border_width:
        style["borderWidth"] = pt(border_width)
    if radius:
        style["borderRadius"] = mm(radius)
    el = {"kind": "box", "id": id_, "placement": placement, "style": style}
    if parity:
        el["parity"] = parity
    if pages:
        el["pages"] = pages
    return el


def image_el(id_: str, resource_id: str, placement: dict, *, parity: str | None = None,
             pages: str | None = None) -> dict:
    el = {"kind": "image", "id": id_, "placement": placement, "resourceId": resource_id}
    if parity:
        el["parity"] = parity
    if pages:
        el["pages"] = pages
    return el


