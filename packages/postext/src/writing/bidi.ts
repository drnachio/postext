// Lines

/**
 * The levels of one line of a paragraph, `[start, end)` in UTF-16 units,
 * after rule L1: segment and paragraph separators, and the white space and
 * isolate controls before them or at the end of the line, go back to the
 * paragraph level (a space that ends an Arabic line inside an English
 * paragraph sits at the line's right end, not inside the Arabic run).
 * Index 0 of the result is the line's first unit.
 */
export function lineLevels(par: BidiParagraph, start = 0, end = par.levels.length): Uint8Array {
  const out = par.levels.slice(start, end);
  const cls = par.classes;
  let trailing = true;
  for (let i = end - 1; i >= start; i--) {
    const c = cls[i]!;
    if (c === TAIL) continue;
    if (c === S || c === B) {
      out[i - start] = par.paragraphLevel;
      trailing = true;
    } else if (trailing && (c === WS || c === LRI || c === RLI || c === FSI || c === PDI || isRemoved(c))) {
      out[i - start] = par.paragraphLevel;
    } else trailing = false;
  }
  // A pair's second unit keeps its first unit's level.
  for (let i = start + 1; i < end; i++) if (cls[i] === TAIL) out[i - start] = out[i - start - 1]!;
  return out;
}

/**
 * Rule L2 on any sequence of items with levels (characters, or a line's
 * segments with the level of each): the indices of `levels[start..end)`
 * from left to right. Every run at or above each odd level is reversed,
 * from the highest level down.
 */
export function visualOrder(levels: ArrayLike<number>, start = 0, end = levels.length): number[] {
  const order: number[] = [];
  let max = 0;
  let minOdd = 255;
  for (let i = start; i < end; i++) {
    order.push(i);
    const lv = levels[i]!;
    if (lv > max) max = lv;
    if (lv & 1 && lv < minOdd) minOdd = lv;
  }
  for (let lv = max; lv >= minOdd && lv > 0; lv--) {
    for (let k = 0; k < order.length; k++) {
      if (levels[order[k]!]! < lv) continue;
      let e = k;
      while (e < order.length && levels[order[e]!]! >= lv) e++;
      for (let a = k, b = e - 1; a < b; a++, b--) {
        const t = order[a]!;
        order[a] = order[b]!;
        order[b] = t;
      }
      k = e;
    }
  }
  return order;
}

/**
 * The characters of one line of a paragraph in visual order, left to right
 * (rules L1 and L2): the index, in the paragraph's text, of each code
 * point's first unit.
 */
export function lineVisualOrder(par: BidiParagraph, start = 0, end = par.levels.length): number[] {
  const lv = lineLevels(par, start, end);
  const order = visualOrder(lv);
  const out: number[] = [];
  for (const k of order) if (par.classes[start + k] !== TAIL) out.push(start + k);
  return out;
}

/** A run of one level within a line: `[start, end)` in the paragraph's
 *  text, painted right to left when `level` is odd. */
export interface BidiRun {
  start: number;
  end: number;
  level: number;
}

/**
 * One line of a paragraph as runs of one level each, in visual order (left
 * to right): what a renderer paints, each run shaped in its own direction
 * (an odd level is right to left). Rules L1 and L2.
 */
export function lineRuns(par: BidiParagraph, start = 0, end = par.levels.length): BidiRun[] {
  const lv = lineLevels(par, start, end);
  const runs: BidiRun[] = [];
  for (let i = 0; i < lv.length;) {
    let e = i + 1;
    while (e < lv.length && lv[e] === lv[i]) e++;
    runs.push({ start: start + i, end: start + e, level: lv[i]! });
    i = e;
  }
  const runLevels = runs.map((r) => r.level);
  return visualOrder(runLevels).map((k) => runs[k]!);
}

/** One run of a marker read at a right-to-left level ({@link markerRuns}). */
export interface MarkerRun {
  text: string;
  /** Where the run starts in the marker's text (its reading order). */
  start: number;
  /** At an odd level: painted right to left, its brackets mirrored. */
  rtl?: true;
}

/**
 * A marker that reads right to left (`VDTBlock.bulletDirection`) as the
 * runs a renderer paints, in visual order (from the sheet's left to its
 * right): `1-` gives the hyphen, then the number. Each run is one bidi
 * level (UAX #9, rules L1 and L2, at a right-to-left paragraph level); in
 * an Arabic-script document (`'rtl-arabic'`) European digits read as
 * Arabic numbers (#665).
 */
export function markerRuns(text: string, direction: 'rtl' | 'rtl-arabic'): MarkerRun[] {
  const par = resolveParagraph(text, 'rtl', undefined, direction === 'rtl-arabic' ? { arabicNumbers: true } : undefined);
  return lineRuns(par).map((r) => ({ text: text.slice(r.start, r.end), start: r.start, ...(r.level & 1 ? { rtl: true as const } : {}) }));
}

/** Whether a marker's order differs when its leading European digits read
 *  as Arabic numbers (`BidiOptions.arabicNumbers`, #665). */
export function arabicMarkNeeded(text: string): boolean {
  if (!/[0-9]/.test(text)) return false;
  const plain = markerRuns(text, 'rtl');
  const arabic = markerRuns(text, 'rtl-arabic');
  return plain.length !== arabic.length || plain.some((r, i) => r.text !== arabic[i]!.text);
}

/** The Arabic letter mark: no width, and rule W2 reads the European
 *  number after it as an Arabic one. */
const ARABIC_LETTER_MARK = '\u061C';

/**
 * A marker that reads right to left as the one text a browser sets right
 * to left in that order ({@link markerRuns}): its own, with an Arabic
 * letter mark before it where an Arabic-script document reads its leading
 * European digits as an Arabic number (`3-1`, the 3 on the right). What
 * the canvas paints, the HTML writes and, in a document shaped in its own
 * language, the layout measures (#770).
 */
export function markerSetText(text: string, direction: 'rtl' | 'rtl-arabic'): string {
  return direction === 'rtl-arabic' && arabicMarkNeeded(text) ? ARABIC_LETTER_MARK + text : text;
}
