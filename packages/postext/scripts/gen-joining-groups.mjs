#!/usr/bin/env node
// Generate src/measure/joiningGroups.ts, the Arabic letters' Unicode
// Joining_Group (the skeleton family a letter belongs to: beh, hah, seen…),
// which the kashida patterns (src/measure/kashidaPatterns.ts) match on:
//
//   node scripts/gen-joining-groups.mjs <ucd-dir>
//
// <ucd-dir> holds ArabicShaping.txt, e.g. fetched with
//   curl -O https://www.unicode.org/Public/UCD/latest/ucd/ArabicShaping.txt
// Only the Arabic blocks are kept (U+0600–08FF): the patterns are Arabic.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = process.argv[2];
if (!dir) {
  console.error('usage: node scripts/gen-joining-groups.mjs <ucd-dir>');
  process.exit(1);
}
const text = readFileSync(join(dir, 'ArabicShaping.txt'), 'utf8');
const version = /ArabicShaping-(\d+\.\d+\.\d+)\.txt/.exec(text)?.[1] ?? '?';

/** `TEH MARBUTA GOAL` → `Teh_Marbuta_Goal`, the property's long value name. */
const longName = (g) => g.trim().toLowerCase().split(/\s+/).map((w) => w[0].toUpperCase() + w.slice(1)).join('_');

const names = [];
const ranges = [];
for (const line of text.split('\n')) {
  const m = /^([0-9A-F]+);[^;]*;\s*\w+;\s*(.+?)\s*$/.exec(line);
  if (!m) continue;
  const cp = parseInt(m[1], 16);
  if (cp < 0x0600 || cp > 0x08FF || m[2] === 'No_Joining_Group') continue;
  const name = longName(m[2]);
  let idx = names.indexOf(name);
  if (idx < 0) idx = names.push(name) - 1;
  const last = ranges[ranges.length - 1];
  if (last && last[1] === cp - 1 && last[2] === idx) last[1] = cp;
  else ranges.push([cp, cp, idx]);
}

const rows = [];
let row = [];
for (const [a, b, v] of ranges) {
  row.push(`0x${a.toString(16).toUpperCase()},0x${b.toString(16).toUpperCase()},${v}`);
  if (row.length === 8) {
    rows.push(`  ${row.join(', ')},`);
    row = [];
  }
}
if (row.length) rows.push(`  ${row.join(', ')},`);

const out = `// Generated by scripts/gen-joining-groups.mjs from the Unicode Character
// Database (ArabicShaping-${version}). Do not edit by hand: re-run the script
// on a newer UCD instead.

/** Joining_Group long names, indexed by the values of
 *  {@link JOINING_GROUP_RANGES}. */
export const JOINING_GROUP_NAMES: readonly string[] = [
${names.map((n) => `  '${n}',`).join('\n')}
];

/** Joining_Group of the Arabic blocks (U+0600–08FF): [first, last, group]
 *  for every range with a group, merged, in code point order. */
export const JOINING_GROUP_RANGES: readonly number[] = [
${rows.join('\n')}
];
`;
const target = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'measure', 'joiningGroups.ts');
writeFileSync(target, out);
console.log(`wrote ${target}: ${names.length} groups, ${ranges.length} ranges`);
