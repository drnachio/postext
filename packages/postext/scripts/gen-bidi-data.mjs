#!/usr/bin/env node
// Generate src/bidiData.ts, the Unicode tables of the bidi algorithm
// (src/bidi.ts), from a directory holding the UCD files:
//
//   node scripts/gen-bidi-data.mjs <ucd-dir>
//
// <ucd-dir> holds DerivedBidiClass.txt and DerivedJoiningType.txt (from
// ucd/extracted/), BidiBrackets.txt and BidiMirroring.txt, e.g. fetched with
//   curl -O https://www.unicode.org/Public/UCD/latest/ucd/extracted/DerivedBidiClass.txt
// Re-run it when the engine moves to a new Unicode version. When the
// directory also holds BidiCharacterTest.txt and BidiTest.txt, the script
// writes the conformance subsets the tests read
// (src/__tests__/fixtures/bidi/*-subset.txt; the full files are 15 MB).
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = process.argv[2];
if (!dir) {
  console.error('usage: node scripts/gen-bidi-data.mjs <ucd-dir>');
  process.exit(1);
}
const read = (f) => readFileSync(join(dir, f), 'utf8');
const versionOf = (text) => /-(\d+\.\d+\.\d+)\.txt/.exec(text)?.[1] ?? '?';

// Bidi_Class codes, in the order of BIDI_CLASS_NAMES in bidi.ts.
const BIDI = ['L', 'R', 'AL', 'EN', 'ES', 'ET', 'AN', 'CS', 'NSM', 'BN', 'B', 'S', 'WS', 'ON',
  'LRE', 'LRO', 'RLE', 'RLO', 'PDF', 'LRI', 'RLI', 'FSI', 'PDI'];
const LONG = {
  Left_To_Right: 'L', Right_To_Left: 'R', Arabic_Letter: 'AL', European_Number: 'EN',
  European_Separator: 'ES', European_Terminator: 'ET', Arabic_Number: 'AN', Common_Separator: 'CS',
  Nonspacing_Mark: 'NSM', Boundary_Neutral: 'BN', Paragraph_Separator: 'B', Segment_Separator: 'S',
  White_Space: 'WS', Other_Neutral: 'ON',
};
// Joining_Type codes: 0 = U (non-joining, the default), then these.
const JT = ['U', 'C', 'D', 'R', 'L', 'T'];
const JT_LONG = { Non_Joining: 'U', Join_Causing: 'C', Dual_Joining: 'D', Right_Joining: 'R', Left_Joining: 'L', Transparent: 'T' };

/** Fill `table` from a derived property file: the @missing lines in order,
 *  then the explicit lines. */
function fill(text, table, codes, long) {
  const code = (v) => {
    const short = long[v] ?? v;
    const i = codes.indexOf(short);
    if (i < 0) throw new Error(`unknown value ${v}`);
    return i;
  };
  for (const m of text.matchAll(/^# @missing: ([0-9A-F]+)\.\.([0-9A-F]+); (\w+)/gm)) {
    table.fill(code(m[3]), parseInt(m[1], 16), parseInt(m[2], 16) + 1);
  }
  for (const line of text.split('\n')) {
    const m = /^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\w+)/.exec(line);
    if (!m) continue;
    const lo = parseInt(m[1], 16);
    const hi = m[2] ? parseInt(m[2], 16) : lo;
    table.fill(code(m[3]), lo, hi + 1);
  }
}

/** Runs of a table that differ from `def`: [first, last, value] merged. */
function ranges(table, def) {
  const out = [];
  let cp = 0;
  while (cp < table.length) {
    const v = table[cp];
    let end = cp;
    while (end + 1 < table.length && table[end + 1] === v) end++;
    if (v !== def) out.push([cp, end, v]);
    cp = end + 1;
  }
  return out;
}

const hex = (n) => `0x${n.toString(16).toUpperCase()}`;
/** Rows of `[first, last, value]` triples, wrapped near 110 columns. */
function rows(triples, fmt) {
  const items = triples.map(fmt);
  const lines = [];
  let line = '  ';
  for (const it of items) {
    if (line.length + it.length + 2 > 112) {
      lines.push(line.trimEnd());
      line = '  ';
    }
    line += `${it}, `;
  }
  if (line.trim()) lines.push(line.trimEnd().replace(/,$/, ''));
  return lines.join('\n');
}

const bidiText = read('DerivedBidiClass.txt');
const bidi = new Uint8Array(0x110000);
fill(bidiText, bidi, BIDI, LONG);
const bidiRanges = ranges(bidi, 0);

const jtText = read('DerivedJoiningType.txt');
const jt = new Uint8Array(0x110000);
fill(jtText, jt, JT, JT_LONG);
const jtRanges = ranges(jt, 0);

const bracketsText = read('BidiBrackets.txt');
const pairs = [];
for (const line of bracketsText.split('\n')) {
  const m = /^([0-9A-F]+); ([0-9A-F]+); o/.exec(line);
  if (m) pairs.push([parseInt(m[1], 16), parseInt(m[2], 16)]);
}
const mirrorText = read('BidiMirroring.txt');
const mirrors = [];
for (const line of mirrorText.split('\n')) {
  const m = /^([0-9A-F]+); ([0-9A-F]+)/.exec(line);
  if (m) mirrors.push([parseInt(m[1], 16), parseInt(m[2], 16)]);
}
mirrors.sort((a, b) => a[0] - b[0]);

const out = `// Generated by scripts/gen-bidi-data.mjs from the Unicode Character Database
// (DerivedBidiClass-${versionOf(bidiText)}, BidiBrackets-${versionOf(bracketsText)},
// BidiMirroring-${versionOf(mirrorText)}, DerivedJoiningType-${versionOf(jtText)}). Do not edit by hand:
// re-run the script on a newer UCD instead.

/** Bidi_Class: [first, last, class] for every range that is not \`L\`, merged,
 *  in code point order. Classes are indices into \`BIDI_CLASS_NAMES\`
 *  (bidi.ts). */
export const BIDI_CLASS_RANGES: readonly number[] = [
${rows(bidiRanges, ([a, b, v]) => `${hex(a)},${hex(b)},${v}`)}
];

/** Joining_Type: [first, last, type] for every range that is not \`U\`, merged,
 *  in code point order: 1 = C, 2 = D, 3 = R, 4 = L, 5 = T. */
export const JOINING_TYPE_RANGES: readonly number[] = [
${rows(jtRanges, ([a, b, v]) => `${hex(a)},${hex(b)},${v}`)}
];

/** Bidi_Paired_Bracket: [opening, closing] pairs, in code point order of the
 *  opening bracket. */
export const BRACKET_PAIRS: readonly number[] = [
${rows(pairs, ([a, b]) => `${hex(a)},${hex(b)}`)}
];

/** Bidi_Mirroring_Glyph: [code point, mirror] pairs in code point order. */
export const MIRROR_PAIRS: readonly number[] = [
${rows(mirrors, ([a, b]) => `${hex(a)},${hex(b)}`)}
];
`;
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'src', 'bidiData.ts');
writeFileSync(target, out);

// Conformance subsets: deterministic, so a regenerated subset only changes
// with the data.
const FIXTURES = join(root, 'src', '__tests__', 'fixtures', 'bidi');
mkdirSync(FIXTURES, { recursive: true });
if (existsSync(join(dir, 'BidiCharacterTest.txt'))) {
  // The hand-made cases at the head of the file (the UAX #9 examples, the
  // bracket, mark and isolate cases: the first HEAD), then one in CHAR_STEP
  // of the generated ones.
  const HEAD = 400;
  const CHAR_STEP = 20;
  const text = read('BidiCharacterTest.txt');
  const outLines = [
    `# Subset of BidiCharacterTest-${versionOf(text)}.txt written by scripts/gen-bidi-data.mjs: the first ${HEAD}`,
    `# cases, then one in ${CHAR_STEP}. Set POSTEXT_UCD_DIR to run the full file.`,
  ];
  let i = 0;
  for (const line of text.split('\n')) {
    if (line.startsWith('#') || line.trim() === '') continue;
    if (i < HEAD || (i - HEAD) % CHAR_STEP === 0) outLines.push(line);
    i++;
  }
  writeFileSync(join(FIXTURES, 'BidiCharacterTest-subset.txt'), `${outLines.join('\n')}\n`);
}
if (existsSync(join(dir, 'BidiTest.txt'))) {
  // Every @Levels / @Reorder line, one data line in TEST_STEP.
  const TEST_STEP = 40;
  const text = read('BidiTest.txt');
  const outLines = [
    `# Subset of BidiTest-${versionOf(text)}.txt written by scripts/gen-bidi-data.mjs: every @Levels and`,
    `# @Reorder line, one data line in ${TEST_STEP}. Set POSTEXT_UCD_DIR to run the full file.`,
  ];
  let i = 0;
  let pending = [];
  for (const line of text.split('\n')) {
    if (line.startsWith('#') || line.trim() === '') continue;
    if (line.startsWith('@')) {
      pending.push(line);
      continue;
    }
    if (i++ % TEST_STEP !== 0) continue;
    outLines.push(...pending, line);
    pending = [];
  }
  writeFileSync(join(FIXTURES, 'BidiTest-subset.txt'), `${outLines.join('\n')}\n`);
}
console.log(`wrote ${target}: ${bidiRanges.length} bidi ranges, ${jtRanges.length} joining ranges, ${pairs.length} bracket pairs, ${mirrors.length} mirrors`);
