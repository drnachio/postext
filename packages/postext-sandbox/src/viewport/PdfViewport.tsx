'use client';

import { useCallback, useEffect, useMemo, useRef, useState } from 'react';
import {
  resolveDebugConfig,
  resolvePdfGenerationConfig,
  type LayoutContinuation,
  type PostextConfig,
  type Resource,
} from 'postext';
import { renderToPdf } from 'postext-pdf';
import { useBookPages, useChapterPlan, useSandboxDispatch, useSandboxSelector, useLayoutSource } from '../context/SandboxContext';
import { composeBookMemo } from '../book/compose';
import { chapterLayoutFromDoc } from '../book/pagination';
import type { ComposedBook } from '../book/types';
import { ensureConfigFontsLoaded, onCustomFontsChanged } from '../controls/fontLoader';
import { readViewHash } from '../storage/viewHash';
import { withHyphenationLocale } from '../controls/hyphenation';
import { useLayoutWorker, type BuildProgress } from '../worker/useLayoutWorker';
import { buildPdfResourceBytes } from './pdfResourceBytes';
import { PdfPreview } from './PdfPreview';
import { PdfToolbar } from './PdfToolbar';
import { createPdfFontProvider } from './pdfFontProvider';
import { useFloatingToolbarShell } from './useFloatingToolbarShell';

/** The PDF tab is the one place the whole book can be rendered as one
 *  continuous document; by default it shows the active chapter continued
 *  after the ones before it, like the other previews. */
export function PdfViewport() {
  const dispatch = useSandboxDispatch();
  const chapterSource = useLayoutSource();
  const currentPlan = useChapterPlan(chapterSource.chapterId);
  const scope = useSandboxSelector((s) => s.pdfScope);
  const chapters = useSandboxSelector((s) => s.chapters);
  const bookPages = useBookPages();
  const config = useSandboxSelector((s) => s.config);
  const resources = useSandboxSelector((s) => s.resources);
  const storeReady = useSandboxSelector((s) => s.storeReady);
  const locale = useSandboxSelector((s) => s.locale);
  const [bytesUrl, setBytesUrl] = useState<string | null>(null);
  const [generating, setGenerating] = useState(false);
  const [error, setError] = useState<string | null>(null);
  // Where a generation stands: the worker's placement progress while the
  // document is laid out, then the (unmetered) render to PDF bytes.
  const [progress, setProgress] = useState<BuildProgress | null>(null);
  const [phase, setPhase] = useState<'layout' | 'render' | null>(null);
  // Dirty = inputs changed since the last successful render. Canvas/HTML
  // auto-relayout, but the PDF viewer only regenerates on explicit request,
  // so the toolbar needs to announce that the preview is out of date.
  const [dirty, setDirty] = useState(false);
  const bytesRef = useRef<Uint8Array | null>(null);
  const providerRef = useRef(createPdfFontProvider());
  const currentUrlRef = useRef<string | null>(null);
  const hasAutoGeneratedRef = useRef(false);
  const renderedSourceRef = useRef<ComposedBook | null>(null);
  const renderedContinuationRef = useRef<string | null>(null);
  const renderedConfigRef = useRef<PostextConfig | null>(null);
  const renderedResourcesRef = useRef<Resource[] | null>(null);
  const layoutWorker = useLayoutWorker();

  const book = useMemo(
    () => (scope === 'book' ? composeBookMemo(chapters) : chapterSource.book),
    [scope, chapters, chapterSource],
  );
  const continuation: LayoutContinuation | undefined = scope === 'book' ? undefined : chapterSource.continuation;
  // What the continuation changes in the output, as a string: the plan is
  // rebuilt (new objects) far more often than its content changes.
  const continuationSig = scope === 'book'
    ? 'book'
    : `${chapterSource.plan.continuationKey}|${continuation?.pageIndexOffset ?? ''}|${continuation?.pageNumbering?.startAt ?? ''}`;

  const effectiveConfig = useMemo((): PostextConfig => withHyphenationLocale(config, locale), [config, locale]);

  // The reader's page (`#chapter=C&page=P`, kept by the canvas / HTML
  // viewers as the book page number) in the rendered document: the
  // chapter's pages sit at `bookPages[chapter]` (first content page index
  // and number) — unknown until the chapters before it are paginated, in
  // which case the chapter's first content page is opened. A chapter
  // render starts at the chapter's first physical page. Read on every
  // render: the preview only picks it up when a new document lands.
  const chapterIndex = chapters.findIndex((c) => c.id === chapterSource.chapterId);
  const hash = readViewHash();
  // The source's plan is stable across layout records (see
  // `useLayoutSource`); the current record is read from the live plan.
  const leadingBlank = currentPlan.layout?.leadingBlankPages ?? 0;
  const pages = bookPages[chapterSource.chapterId];
  const wanted = hash.chapter === null || hash.chapter === chapterIndex ? hash.page : null;
  const offsetInChapter = pages && wanted !== null ? Math.max(0, wanted - pages.pageNumberValue) : 0;
  let openPage: number | null = leadingBlank + offsetInChapter;
  if (scope === 'book') {
    openPage = pages ? pages.pageIndex + offsetInChapter : null;
  }

  const regenerate = useCallback(async () => {
    setGenerating(true);
    setError(null);
    setProgress(null);
    setPhase('layout');
    const snapshotSource = book;
    const snapshotChapter = scope === 'chapter' ? chapterSource : null;
    const snapshotContinuation = continuation;
    const snapshotSig = continuationSig;
    const snapshotConfig = effectiveConfig;
    const snapshotStateConfig = config;
    const snapshotResources = resources;
    try {
      await ensureConfigFontsLoaded(snapshotConfig);
      const doc = await layoutWorker.build(
        { markdown: snapshotSource.markdown, metadata: snapshotSource.metadata, resources: snapshotResources, continuation: snapshotContinuation },
        snapshotConfig,
        { onProgress: setProgress },
      );
      setPhase('render');
      // A chapter render counts as its layout for the chapters after it.
      if (snapshotChapter) {
        const layout = chapterLayoutFromDoc(doc, snapshotChapter.plan, { markdown: snapshotChapter.chapterMarkdown, config: snapshotStateConfig, resources: snapshotResources });
        if (layout) dispatch({ type: 'SET_CHAPTER_LAYOUT', payload: layout });
      }
      const debug = resolveDebugConfig(snapshotConfig.debug);
      const pdfGen = resolvePdfGenerationConfig(snapshotConfig.pdfGeneration);
      const resourceBytes = await buildPdfResourceBytes(snapshotResources, snapshotConfig);
      const bytes = await renderToPdf(doc, {
        fontProvider: providerRef.current,
        pageNegative: debug.pageNegative.enabled,
        outlines: pdfGen.outlines,
        colorSpace: pdfGen.forceColorSpace ? pdfGen.colorSpace : 'rgb',
        accessible: pdfGen.accessible,
        resourceBytes: (fileId) => resourceBytes.get(fileId),
      });
      bytesRef.current = bytes;
      const copy = bytes.slice();
      const blob = new Blob([copy.buffer], { type: 'application/pdf' });
      const url = URL.createObjectURL(blob);
      if (currentUrlRef.current) URL.revokeObjectURL(currentUrlRef.current);
      currentUrlRef.current = url;
      setBytesUrl(url);
      renderedSourceRef.current = snapshotSource;
      renderedContinuationRef.current = snapshotSig;
      renderedConfigRef.current = snapshotConfig;
      renderedResourcesRef.current = snapshotResources;
      setDirty(false);
    } catch (err) {
      console.error('[PdfViewport] Render error:', err);
      setError(err instanceof Error ? err.message : String(err));
      bytesRef.current = null;
    } finally {
      setGenerating(false);
      setPhase(null);
      setProgress(null);
    }
  }, [book, scope, chapterSource, continuation, continuationSig, effectiveConfig, config, resources, layoutWorker, dispatch]);

  // A scope switch (current chapter ↔ whole book) is a request for the
  // other document: regenerate right away instead of just flagging the
  // preview stale. The first generation waits for the store as below.
  const generatedScopeRef = useRef(scope);
  useEffect(() => {
    if (!hasAutoGeneratedRef.current || generatedScopeRef.current === scope) return;
    generatedScopeRef.current = scope;
    void regenerate();
  }, [scope, regenerate]);

  // Dirty = current markdown/config/resources differ from the snapshot of the
  // last successful render. Set whenever any drifts; cleared inside regenerate.
  useEffect(() => {
    if (!hasAutoGeneratedRef.current) return;
    if (renderedSourceRef.current === null) return;
    const changed =
      renderedSourceRef.current !== book ||
      renderedContinuationRef.current !== continuationSig ||
      renderedConfigRef.current !== effectiveConfig ||
      renderedResourcesRef.current !== resources;
    if (changed) setDirty(true);
  }, [book, continuationSig, effectiveConfig, resources]);

  // A custom family whose definition lands after the last render (a preset
  // finishing its load, an upload from the Fonts panel) leaves the PDF
  // painted from stale bytes; flag it like any other input change.
  useEffect(() => {
    return onCustomFontsChanged(() => {
      if (renderedConfigRef.current !== null) setDirty(true);
    });
  }, []);

  // Auto-generate once the store has hydrated: resources arrive from
  // IndexedDB after mount, and a build before then renders every `:ref` as
  // an unresolved "?" — which this viewport would keep, since it only
  // regenerates on request.
  useEffect(() => {
    if (!storeReady || hasAutoGeneratedRef.current) return;
    hasAutoGeneratedRef.current = true;
    void regenerate();
  }, [storeReady, regenerate]);

  useEffect(() => {
    return () => {
      if (currentUrlRef.current) {
        URL.revokeObjectURL(currentUrlRef.current);
        currentUrlRef.current = null;
      }
    };
  }, []);

  const handleDownload = useCallback(() => {
    const bytes = bytesRef.current;
    if (!bytes) return;
    const copy = bytes.slice();
    const blob = new Blob([copy.buffer], { type: 'application/pdf' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    const metaTitle = typeof book.metadata.title === 'string' ? book.metadata.title : undefined;
    const title = metaTitle ?? book.markdown.match(/^#\s+(.+)$/m)?.[1]?.trim() ?? 'document';
    a.download = `${title.replace(/[^a-z0-9-_]+/gi, '-')}.pdf`;
    document.body.appendChild(a);
    a.click();
    a.remove();
    setTimeout(() => URL.revokeObjectURL(url), 1000);
  }, [book]);

  const handlePrint = useCallback(() => {
    if (!bytesUrl) return;
    const iframe = document.querySelector<HTMLIFrameElement>('iframe[data-postext-pdf="true"]');
    if (!iframe?.contentWindow) return;
    try {
      iframe.contentWindow.focus();
      iframe.contentWindow.print();
    } catch {
      window.open(bytesUrl, '_blank');
    }
  }, [bytesUrl]);

  // Dirty also forces visibility: the recalc button must be reachable the
  // moment something goes stale, otherwise the floating toolbar may be off
  // screen and the user can't act on the arrow cue.
  const shell = useFloatingToolbarShell('pdf', generating || dirty);

  return (
    <div className="relative h-full w-full" {...shell.containerProps}>
      <PdfPreview
        bytesUrl={bytesUrl}
        openPage={openPage}
        generating={generating}
        progress={progress}
        phase={phase}
        error={error}
      />
      <div {...shell.hoverStripProps} />
      <PdfToolbar
        onRegenerate={regenerate}
        onDownload={handleDownload}
        onPrint={handlePrint}
        onTogglePin={shell.togglePin}
        canDownload={!!bytesUrl && !generating}
        canPrint={!!bytesUrl && !generating}
        generating={generating}
        pinned={shell.pinned}
        hidden={shell.hidden}
        dirty={dirty}
        {...shell.toolbarHoverProps}
      />
    </div>
  );
}
